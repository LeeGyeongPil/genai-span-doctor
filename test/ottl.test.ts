// AC-6 (generation side): statements only for observed dialects, ordered sum -> copy -> delete, nil guards.
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { test } from 'node:test';
import { runAudit } from '../src/audit.js';
import { makeTranslator } from '../src/i18n.js';
import { readSpans } from '../src/otlp.js';
import { generateOttl } from '../src/ottl.js';
import { loadRules, wantedKeys } from '../src/rules.js';
import { cli, example, fixture, ROOT, tmpDir } from './helpers.js';

const rules = loadRules();
const t = makeTranslator('en');

function ottlFor(file: string, deleteSource = false) {
  const { spans, files } = readSpans(file, wantedKeys(rules));
  const result = runAudit(spans, rules, { backendName: 'otel', assumeCacheExcluded: new Set(), files, t });
  return generateOttl(result.analyses, { rules, t, version: '0.0.0-test', deleteSource, assumeCacheExcluded: new Set() });
}

test('AC-6: output equals the golden file (UPDATE_GOLDEN=1 rewrites it)', () => {
  const golden = join(ROOT, 'test', 'golden', 'five-dialects.ottl.yaml');
  const yaml = ottlFor(fixture('five-dialects.otlp.json')).yaml;
  if (process.env.UPDATE_GOLDEN === '1') writeFileSync(golden, yaml);
  assert.equal(yaml, readFileSync(golden, 'utf8'));
});

test('AC-6: flat sum and OpenInference cache condition are present', () => {
  const s = ottlFor(fixture('five-dialects.otlp.json')).statements.map((x) => x.text);
  assert.ok(s.some((x) => x.includes('span.attributes["input_tokens"] + span.attributes["gen_ai.usage.cache_read.input_tokens"] + span.attributes["gen_ai.usage.cache_creation.input_tokens"]')));
  assert.ok(s.some((x) => x.includes('> span.attributes["llm.token_count.prompt"]')));
});

test('AC-6: every set/delete statement is guarded against nil', () => {
  for (const s of ottlFor(fixture('five-dialects.otlp.json')).statements) {
    if (s.text.startsWith('set(')) assert.match(s.text, / where .*!= nil/, s.text);
  }
});

test('AC-6: only observed dialects produce statements', () => {
  const onlyVercel = ottlFor(fixture('dir/part1.json')).statements.map((x) => x.text).join('\n');
  assert.ok(onlyVercel.includes('gen_ai.usage.prompt_tokens'));
  assert.ok(!onlyVercel.includes('"ai.usage.'));
  assert.ok(!onlyVercel.includes('llm.token_count'));
});

test('AC-6: a conformant trace needs no statements', () => {
  assert.equal(ottlFor(fixture('clean.otlp.json')).statements.length, 0);
});

test('AC-6: phases are ordered cache -> sum -> copy -> delete', () => {
  const phases = ottlFor(fixture('five-dialects.otlp.json'), true).statements.map((x) => x.phase);
  const order = ['cache', 'sum', 'copy', 'delete'];
  const idx = phases.map((p) => order.indexOf(p));
  assert.deepEqual(idx, [...idx].sort((a, b) => a - b));
  assert.ok(phases.includes('delete'));
});

test('AC-6: sources are deleted only with --ottl-delete-source', () => {
  const without = ottlFor(fixture('five-dialects.otlp.json')).statements.map((x) => x.text).join('\n');
  const withDelete = ottlFor(fixture('five-dialects.otlp.json'), true).statements.map((x) => x.text).join('\n');
  assert.ok(!without.includes('delete_key'));
  assert.ok(withDelete.includes('delete_key(span.attributes, "cache_read_tokens")'));
  assert.ok(!withDelete.includes('delete_key(span.attributes, "gen_ai.usage.input_tokens")'));
});

test('AC-6: OpenLLMetry spans with cache > input get an in-place correction', () => {
  const s = ottlFor(example('mixed-dialects.otlp.json')).statements.map((x) => x.text);
  assert.ok(s.some((x) => x.includes('gen_ai.usage.cache_read_input_tokens') && x.startsWith('set(span.attributes["gen_ai.usage.cache_read.input_tokens"]')));
  assert.ok(s.some((x) => x.startsWith('set(span.attributes["gen_ai.usage.input_tokens"], span.attributes["gen_ai.usage.input_tokens"] + ')));
});

test('CLI: --emit-ottl file writes YAML, stdout keeps the report', () => {
  const file = join(tmpDir('gsd-'), 'out.yaml');
  const r = cli([fixture('five-dialects.otlp.json'), '--emit-ottl', file, '--fail-on', 'none']);
  assert.equal(r.code, 0, r.stderr);
  assert.match(r.stdout, /Summary/);
  assert.match(readFileSync(file, 'utf8'), /transform\/genai:/);
  assert.match(r.stderr, /Wrote Collector transform snippet/);
});

test('CLI: --emit-ottl without a file sends YAML to stdout and the report to stderr', () => {
  const r = cli([fixture('five-dialects.otlp.json'), '--emit-ottl', '--fail-on', 'none']);
  assert.match(r.stdout, /^# Generated by genai-span-doctor/);
  assert.match(r.stderr, /Summary/);
});
